CREATE TABLE locations (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           name VARCHAR(100) NOT NULL,
                           code VARCHAR(50) NOT NULL,

                           address TEXT,
                           phone VARCHAR(30),

                           time_zone VARCHAR(64) NOT NULL DEFAULT 'Asia/Phnom_Penh',

                           status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

                           created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                           CONSTRAINT uq_locations_code
                               UNIQUE (code),

                           CONSTRAINT chk_locations_status
                               CHECK (status IN ('ACTIVE', 'INACTIVE'))
);


CREATE TABLE room_types (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            name VARCHAR(100) NOT NULL,
                            code VARCHAR(50) NOT NULL,

                            description TEXT,

                            capacity INTEGER NOT NULL,

                            status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT uq_room_types_code
                                UNIQUE (code),

                            CONSTRAINT chk_room_types_capacity
                                CHECK (capacity > 0),

                            CONSTRAINT chk_room_types_status
                                CHECK (status IN ('ACTIVE', 'INACTIVE'))
);