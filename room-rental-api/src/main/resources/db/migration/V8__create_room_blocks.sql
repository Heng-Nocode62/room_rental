CREATE TABLE room_blocks (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             room_id BIGINT NOT NULL,

                             block_type VARCHAR(30) NOT NULL,

                             status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

                             start_at TIMESTAMPTZ NOT NULL,

                             end_at TIMESTAMPTZ NOT NULL,

                             reason VARCHAR(255),

                             notes TEXT,

                             created_by BIGINT NOT NULL,

                             created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                             updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT fk_room_blocks_room
                                 FOREIGN KEY (room_id)
                                     REFERENCES rooms(id),

                             CONSTRAINT fk_room_blocks_created_by
                                 FOREIGN KEY (created_by)
                                     REFERENCES users(id),

                             CONSTRAINT chk_room_blocks_time
                                 CHECK (end_at > start_at),

                             CONSTRAINT chk_room_blocks_type
                                 CHECK (
                                     block_type IN (
                                                    'MAINTENANCE',
                                                    'CLEANING',
                                                    'PRIVATE_EVENT',
                                                    'RENOVATION',
                                                    'OTHER'
                                         )
                                     ),

                             CONSTRAINT chk_room_blocks_status
                                 CHECK (
                                     status IN (
                                                'ACTIVE',
                                                'CANCELLED',
                                                'COMPLETED'
                                         )
                                     )
);

CREATE INDEX idx_room_blocks_room_time
    ON room_blocks(room_id, start_at, end_at);

CREATE INDEX idx_room_blocks_status
    ON room_blocks(status);