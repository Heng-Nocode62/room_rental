CREATE TABLE pricing_units (
                               id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               code VARCHAR(20) NOT NULL,
                               name VARCHAR(50) NOT NULL,

                               CONSTRAINT uq_pricing_units_code
                                   UNIQUE (code)
);


CREATE TABLE room_prices (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             room_id BIGINT NOT NULL,
                             pricing_unit_id SMALLINT NOT NULL,

                             price NUMERIC(12, 2) NOT NULL,

                             currency_code VARCHAR(3) NOT NULL DEFAULT 'USD',

                             effective_from DATE NOT NULL,
                             effective_to DATE,

                             status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

                             created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT fk_room_prices_room
                                 FOREIGN KEY (room_id)
                                     REFERENCES rooms(id)
                                     ON DELETE CASCADE,

                             CONSTRAINT fk_room_prices_pricing_unit
                                 FOREIGN KEY (pricing_unit_id)
                                     REFERENCES pricing_units(id),

                             CONSTRAINT chk_room_prices_price
                                 CHECK (price >= 0),

                             CONSTRAINT chk_room_prices_dates
                                 CHECK (
                                     effective_to IS NULL
                                         OR effective_to > effective_from
                                     ),

                             CONSTRAINT chk_room_prices_status
                                 CHECK (
                                     status IN ('ACTIVE', 'INACTIVE')
                                     )
);