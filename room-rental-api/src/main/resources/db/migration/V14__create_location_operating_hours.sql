CREATE TABLE location_operating_hours (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                          location_id BIGINT NOT NULL,

                                          day_of_week SMALLINT NOT NULL,

                                          open_time TIME,
                                          close_time TIME,

                                          closed BOOLEAN NOT NULL DEFAULT FALSE,

                                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                          CONSTRAINT fk_location_operating_hours_location
                                              FOREIGN KEY (location_id)
                                                  REFERENCES locations(id)
                                                  ON DELETE CASCADE,

                                          CONSTRAINT uq_location_operating_hours_day
                                              UNIQUE (location_id, day_of_week),

                                          CONSTRAINT chk_location_operating_hours_day
                                              CHECK (day_of_week BETWEEN 1 AND 7),

                                          CONSTRAINT chk_location_operating_hours_time
                                              CHECK (
                                                  closed = TRUE
                                                      OR (
                                                      open_time IS NOT NULL
                                                          AND close_time IS NOT NULL
                                                          AND close_time > open_time
                                                      )
                                                  )
);