CREATE TABLE locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(50) NOT NULL,
    address TEXT,
    phone VARCHAR(30),
    time_zone VARCHAR(64) NOT NULL DEFAULT 'Asia/Phnom_Penh',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    floor INTEGER NOT NULL DEFAULT 1,
    image_url VARCHAR(1000),
    location_bakong_account_id VARCHAR(100),
    telegram_contact VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_locations_code UNIQUE (code),
    CONSTRAINT chk_locations_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE user_location_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_location_role UNIQUE (user_id, location_id, role_id),
    CONSTRAINT fk_user_location_roles_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_location_roles_location FOREIGN KEY (location_id) REFERENCES locations(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_location_roles_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE
);

CREATE TABLE location_operating_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL,
    day_of_week SMALLINT NOT NULL,
    open_time TIME,
    close_time TIME,
    closed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_location_operating_hours_day UNIQUE (location_id, day_of_week),
    CONSTRAINT fk_location_operating_hours_location FOREIGN KEY (location_id) REFERENCES locations(id) ON DELETE CASCADE
);
