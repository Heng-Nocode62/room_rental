CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              reference_no VARCHAR(50) NOT NULL,

                              room_id BIGINT NOT NULL,

                              reserved_by BIGINT NOT NULL,

                              status_id SMALLINT NOT NULL,

                              start_at TIMESTAMPTZ NOT NULL,
                              end_at TIMESTAMPTZ NOT NULL,

                              pricing_unit_id SMALLINT NOT NULL,

                              unit_price NUMERIC(12, 2) NOT NULL,
                              total_amount NUMERIC(12, 2) NOT NULL,

                              currency_code VARCHAR(3) NOT NULL DEFAULT 'USD',

                              purpose VARCHAR(255),

                              contact_name VARCHAR(150),
                              contact_phone VARCHAR(30),
                              company_name VARCHAR(150),

                              notes TEXT,

                              cancelled_at TIMESTAMPTZ,
                              cancelled_by BIGINT,

                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT uq_reservations_reference
                                  UNIQUE (reference_no),

                              CONSTRAINT fk_reservations_room
                                  FOREIGN KEY (room_id)
                                      REFERENCES rooms(id),

                              CONSTRAINT fk_reservations_reserved_by
                                  FOREIGN KEY (reserved_by)
                                      REFERENCES users(id),

                              CONSTRAINT fk_reservations_status
                                  FOREIGN KEY (status_id)
                                      REFERENCES reservation_statuses(id),

                              CONSTRAINT fk_reservations_pricing_unit
                                  FOREIGN KEY (pricing_unit_id)
                                      REFERENCES pricing_units(id),

                              CONSTRAINT fk_reservations_cancelled_by
                                  FOREIGN KEY (cancelled_by)
                                      REFERENCES users(id),

                              CONSTRAINT chk_reservations_time
                                  CHECK (end_at > start_at),

                              CONSTRAINT chk_reservations_unit_price
                                  CHECK (unit_price >= 0),

                              CONSTRAINT chk_reservations_total_amount
                                  CHECK (total_amount >= 0)
);