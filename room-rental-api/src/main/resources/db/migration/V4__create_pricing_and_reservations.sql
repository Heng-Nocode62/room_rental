CREATE TABLE pricing_units (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(50) NOT NULL,
    CONSTRAINT uq_pricing_units_code UNIQUE (code)
);

CREATE TABLE reservation_statuses (
    id SMALLINT PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    CONSTRAINT uq_reservation_statuses_code UNIQUE (code)
);

CREATE TABLE room_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    pricing_unit_id SMALLINT NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    currency_code VARCHAR(3) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_room_prices_room FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
    CONSTRAINT fk_room_prices_pricing_unit FOREIGN KEY (pricing_unit_id) REFERENCES pricing_units(id),
    CONSTRAINT chk_room_prices_price CHECK (price >= 0),
    CONSTRAINT chk_room_prices_dates CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT chk_room_prices_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no VARCHAR(50) NOT NULL,
    room_id BIGINT NOT NULL,
    reserved_by BIGINT NOT NULL,
    status_id SMALLINT NOT NULL,
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    pricing_unit_id SMALLINT NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL,
    currency_code VARCHAR(3) NOT NULL DEFAULT 'USD',
    purpose VARCHAR(255),
    contact_name VARCHAR(150),
    contact_phone VARCHAR(30),
    company_name VARCHAR(150),
    notes TEXT,
    cancelled_at TIMESTAMPTZ,
    cancelled_by BIGINT,
    confirmed_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_reservations_reference UNIQUE (reference_no),
    CONSTRAINT fk_reservations_room FOREIGN KEY (room_id) REFERENCES rooms(id),
    CONSTRAINT fk_reservations_reserved_by FOREIGN KEY (reserved_by) REFERENCES users(id),
    CONSTRAINT fk_reservations_status FOREIGN KEY (status_id) REFERENCES reservation_statuses(id),
    CONSTRAINT fk_reservations_pricing_unit FOREIGN KEY (pricing_unit_id) REFERENCES pricing_units(id),
    CONSTRAINT fk_reservations_cancelled_by FOREIGN KEY (cancelled_by) REFERENCES users(id),
    CONSTRAINT fk_reservations_confirmed_by FOREIGN KEY (confirmed_by) REFERENCES users(id),
    CONSTRAINT chk_reservations_time CHECK (end_at > start_at),
    CONSTRAINT chk_reservations_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_reservations_total_amount CHECK (total_amount >= 0)
);

CREATE TABLE reservation_amenities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL,
    amenity_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    total_price NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_reservation_amenity UNIQUE (reservation_id, amenity_id),
    CONSTRAINT fk_reservation_amenities_reservation FOREIGN KEY (reservation_id) REFERENCES reservations(id) ON DELETE CASCADE,
    CONSTRAINT fk_reservation_amenities_amenity FOREIGN KEY (amenity_id) REFERENCES amenities(id),
    CONSTRAINT chk_reservation_amenities_quantity CHECK (quantity > 0),
    CONSTRAINT chk_reservation_amenities_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_reservation_amenities_total_price CHECK (total_price >= 0)
);

CREATE TABLE room_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    block_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    start_at TIMESTAMPTZ NOT NULL,
    end_at TIMESTAMPTZ NOT NULL,
    reason VARCHAR(255),
    notes TEXT,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_room_blocks_room FOREIGN KEY (room_id) REFERENCES rooms(id),
    CONSTRAINT fk_room_blocks_created_by FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT chk_room_blocks_time CHECK (end_at > start_at),
    CONSTRAINT chk_room_blocks_type CHECK (block_type IN ('MAINTENANCE', 'CLEANING', 'PRIVATE_EVENT', 'RENOVATION', 'OTHER')),
    CONSTRAINT chk_room_blocks_status CHECK (status IN ('ACTIVE', 'CANCELLED', 'COMPLETED'))
);
